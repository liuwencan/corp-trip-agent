CREATE TABLE IF NOT EXISTS t_config (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, config_name VARCHAR(255) NOT NULL,
 config_key VARCHAR(255) NOT NULL, config_value TEXT NOT NULL, remark VARCHAR(255),
 create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP, update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS t_user (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, username VARCHAR(32) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, role VARCHAR(16) NOT NULL DEFAULT 'USER',
 must_change_password BOOLEAN NOT NULL DEFAULT FALSE, credential_version BIGINT NOT NULL DEFAULT 0,
 create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS t_user_password_reset_log (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, target_user_id BIGINT NOT NULL, operator_id BIGINT NOT NULL,
 reason VARCHAR(1000) NOT NULL, create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
